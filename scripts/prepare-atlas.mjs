import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { readJson } from './airport-model.mjs';
import { loadFrozenScenarioSources } from './prepare-capacity.mjs';
import { loadAtlasProfile, prepareCapacityAtlas } from './capacity-atlas.mjs';

const path = relative => fileURLToPath(new URL(relative, import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    if (process.argv.length !== 2) throw new Error('Usage: npm run prepare:atlas');
    const { airport, sources } = loadFrozenScenarioSources(), profile = loadAtlasProfile();
    const atlases = sources.map(({ snapshot, raw }) => prepareCapacityAtlas(snapshot, raw, airport,
      readJson(path(`../src/demo/prepared/${snapshot.case_id}.capacity.json`)), profile));
    const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
    ajv.addSchema(readJson(path('../data/schemas/capacity-atlas-profile.schema.json')));
    const validate = ajv.compile(readJson(path('../data/schemas/capacity-atlas.schema.json')));
    for (const atlas of atlases) if (!validate(atlas)) throw new Error(`Invalid prepared atlas: ${ajv.errorsText(validate.errors)}`);
    for (const atlas of atlases) {
      writeFileSync(path(`../src/demo/prepared/${atlas.case_id}.atlas.json`), `${JSON.stringify(atlas)}\n`);
      console.log(`${atlas.case_id}: ${atlas.days.length} synthetic timing replays; planned and modeled end-of-day; both variants.`);
    }
    writeFileSync(path('../src/demo/atlas-validator.mjs'),
      `// Generated by npm run prepare:atlas. Do not edit manually.\n${standaloneCode(ajv, validate)}\n`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
