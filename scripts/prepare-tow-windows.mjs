import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { readJson } from './airport-model.mjs';
import { loadFrozenScenarioSources } from './prepare-capacity.mjs';
import { prepareTowWindows } from './tow-windows.mjs';

const path = relative => fileURLToPath(new URL(relative, import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    if (process.argv.length !== 2) throw new Error('Usage: npm run prepare:tow-windows');
    const { airport, sources } = loadFrozenScenarioSources();
    const artifacts = sources.map(({ snapshot, raw }) => ({ caseId: snapshot.case_id, evidence: prepareTowWindows(snapshot, raw, airport) }));
    const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
    const validate = ajv.compile(readJson(path('../data/schemas/tow-windows.schema.json')));
    for (const { evidence } of artifacts) if (!validate(evidence)) throw new Error(`Invalid tow-window evidence: ${ajv.errorsText(validate.errors)}`);
    for (const { caseId, evidence } of artifacts) {
      writeFileSync(path(`../src/demo/prepared/${caseId}.tow-windows.json`), `${JSON.stringify(evidence, null, 2)}\n`);
      console.log(`${caseId}: ${evidence.visits.length} one-way assessments; ${evidence.default_tow_minutes} min travel; ` +
        ['baseline', 'tow-options'].map(variant => `${variant}: ${evidence.visits.filter(item => item.variants[variant].destinations.length).length} candidates`).join('; '));
    }
    writeFileSync(path('../src/demo/tow-windows-validator.mjs'),
      `// Generated by npm run prepare:tow-windows. Do not edit manually.\n${standaloneCode(ajv, validate)}\n`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
